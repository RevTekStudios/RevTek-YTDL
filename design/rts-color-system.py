"""Generate portable RTS design tokens; independent of the current app theme."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CORE = {
    "background": "#040A12", "surface": "#0C1723", "surface_raised": "#142333",
    "surface_hover": "#1C3043", "border_subtle": "#243B50", "border_control": "#58748C",
    "text": "#E7EFF5", "text_secondary": "#A9BECE", "text_muted": "#849DB1",
    "brand": "#437798", "brand_deep": "#315F83", "on_accent": "#040A12",
}
FAMILIES = {
    "abyss": ("#DDEBF3", "#B2CEDF", "#7EABC6", "#437798", "#315F83", "#1B3D58", "#0D2235"),
    "ion": ("#E0F8FF", "#B2EEFF", "#7EE0FF", "#50CFFF", "#289ABD", "#176180", "#0B2B3A"),
    "signal": ("#E7F0FF", "#BED7FF", "#93BEFF", "#6BA8FF", "#3B7DCE", "#24528C", "#10263F"),
    "silver": ("#F4F7FA", "#E7EFF5", "#C9D7E2", "#A9BECE", "#849DB1", "#58748C", "#243B50"),
    "amber": ("#FFF4DC", "#FFE2A8", "#FFD17F", "#F5B95F", "#C78B36", "#805923", "#352719"),
    "violet": ("#F1EDFF", "#DCD0FF", "#C5B1FF", "#B49AFF", "#8970C9", "#594585", "#271E3B"),
    "mint": ("#DFFAF0", "#B2EFD9", "#8AE3C3", "#69D6AE", "#3AA37F", "#246D55", "#112F29"),
    "rose": ("#FFECEF", "#FFD0D9", "#FFB1C1", "#FF8FA8", "#CA607A", "#873D52", "#391E2A"),
    "coral": ("#FFF0E9", "#FFD7C3", "#FFBB9D", "#F59A78", "#C37353", "#824B36", "#37241F"),
}
LEVELS = (100, 200, 300, 400, 500, 600, 900)
SCALES = {name: dict(zip(map(str, LEVELS), colors)) for name, colors in FAMILIES.items()}
SEMANTIC = {
    "primary": "#50CFFF", "primary_hover": "#7EE0FF", "primary_pressed": "#289ABD",
    "focus": "#50CFFF", "link": "#93BEFF", "selection_background": "#0B2B3A",
    "selection_foreground": "#B2EEFF", "info": "#6BA8FF", "info_background": "#10263F",
    "success": "#69D6AE", "success_background": "#112F29", "warning": "#F5B95F",
    "warning_background": "#352719", "error": "#FF8FA8", "error_background": "#391E2A",
    "creative": "#B49AFF", "creative_background": "#271E3B",
    "disabled_background": "#142333", "disabled_foreground": "#849DB1",
}

def luminance(value):
    rgb = [int(value[i:i+2], 16)/255 for i in (1, 3, 5)]
    rgb = [c/12.92 if c <= .04045 else ((c+.055)/1.055)**2.4 for c in rgb]
    return sum(c*w for c,w in zip(rgb, (.2126, .7152, .0722)))

def contrast(a, b):
    x, y = sorted((luminance(a), luminance(b)))
    return (y+.05)/(x+.05)

TOKENS = {"name": "RTS Abyss", "version": "0.1", "core": CORE, "semantic": SEMANTIC, "scales": SCALES}
if __name__ == "__main__":
    ROOT.mkdir(exist_ok=True)
    (ROOT / "rts-tokens.json").write_text(json.dumps(TOKENS, indent=2)+"\n")
    lines = ["/* RTS Abyss — generated by rts-color-system.py. Solid colors only. */", ":root {"]
    for group in (CORE, SEMANTIC):
        lines.extend(f"  --rts-{key.replace('_','-')}: {value};" for key, value in group.items())
    for family, scale in SCALES.items():
        lines.extend(f"  --rts-{family}-{step}: {value};" for step, value in scale.items())
    (ROOT / "rts-tokens.css").write_text("\n".join([*lines, "}", ""]))
    checks = []
    for role in ("text", "text_secondary", "text_muted"):
        for surface in ("background", "surface", "surface_raised", "surface_hover"):
            checks.append((role, surface, contrast(CORE[role], CORE[surface]), 4.5))
    for role in ("primary", "primary_hover", "primary_pressed", "success", "warning", "error", "info", "creative"):
        checks.append(("on_accent", role, contrast(CORE["on_accent"], SEMANTIC[role]), 4.5))
    for role in ("info", "success", "warning", "error", "creative"):
        checks.append((role, role+"_background", contrast(SEMANTIC[role], SEMANTIC[role+"_background"]), 4.5))
    checks.append(("border_control", "surface", contrast(CORE["border_control"], CORE["surface"]), 3))
    checks.append(("focus", "surface_hover", contrast(SEMANTIC["focus"], CORE["surface_hover"]), 3))
    report = "# RTS contrast checks\n\nCalculated sRGB relative luminance ratios for these specific pairings.\n\n| Foreground | Background | Ratio | Target |\n|---|---|---|---|\n"
    for fg,bg,ratio,target in checks:
        report += f"| {fg} | {bg} | {ratio:.2f}:1 | {target}:1 |\n"
    (ROOT / "contrast.md").write_text(report)
    failures = [(fg,bg,round(ratio,2)) for fg,bg,ratio,target in checks if ratio < target]
    print(json.dumps({"checked_pairs": len(checks), "failures": failures}))
    if failures:
        raise SystemExit(1)
